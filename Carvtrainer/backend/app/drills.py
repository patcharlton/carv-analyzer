def library_text():
    """The drill library as compact text for the prompt (no video links: those are joined in afterwards)."""
    lines = []
    for drill_id, drill in DRILLS.items():
        parts = [f"[{drill_id}] {drill['name']} ({drill['category']}; suits: {', '.join(drill['techniques'])})"]
        for key, label in (("purpose", "Purpose"), ("execution", "Execution"), ("feel", "Feel"),
                           ("duration", "Duration"), ("terrain", "Terrain"), ("difficulty", "Difficulty"),
                           ("common_mistake", "Common mistake"), ("success_criteria", "Success")):
            if drill.get(key):
                parts.append(f"  {label}: {drill[key]}")
        if drill.get("improves"):
            parts.append(f"  Improves: {', '.join(drill['improves'])}")
        for label, value in (drill.get("notes") or {}).items():
            parts.append(f"  {label}: {value}")
        lines.append("\n".join(parts))
    return "\n\n".join(lines)


def drill_reference(drill_id):
    """Fixed facts about a drill to merge into a plan (None if the id is unknown)."""
    drill = DRILLS.get(drill_id)
    if not drill:
        return None
    keys = ("name", "category", "techniques", "purpose", "execution", "feel", "duration", "terrain",
            "difficulty", "success_criteria", "common_mistake", "improves", "video_url")
    return {"drill_id": drill_id, **{k: drill[k] for k in keys if k in drill}, "notes": drill.get("notes") or {}}
